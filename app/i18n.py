"""On-screen strings of the public app, Korean / English (config/public.yaml app.i18n).

Every word the app shows comes from t(key). The table app/i18n_strings.json is generated by scripts/gen_i18n.py from the
`app:` block of config/glossary.yaml (or the draft config/glossary_app_draft.yaml before the merge). Page code must not
contain Korean text or English sentences (checked by tests/test_app_i18n.py and the bundle check 6).
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

STRINGS_PATH = Path(__file__).with_name("i18n_strings.json")
LANGS = ("ko", "en")
DEFAULT_LANG = "ko"
STATE_KEY = "lang"


class I18nKeyError(KeyError):
    """Raised when a key (or one language of it) is missing: a missing translation must fail loudly, never show blank."""


@lru_cache(maxsize=4)
def _load(path: str) -> dict[str, dict[str, str]]:
    """Read the generated string table {key: {ko, en}} once per file."""
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    return data["strings"]


def strings(path: Path | None = None) -> dict[str, dict[str, str]]:
    """The whole table (used by tests and the bundle check)."""
    return _load(str(path or STRINGS_PATH))


def current_lang() -> str:
    """Language of this browser session: st.session_state['lang'] if set, else Korean (also outside Streamlit)."""
    try:
        import streamlit as st

        v = st.session_state.get(STATE_KEY, DEFAULT_LANG)
    except Exception:  # no Streamlit runtime (plain python, tests)
        v = DEFAULT_LANG
    return v if v in LANGS else DEFAULT_LANG


def init_lang() -> None:
    """Set the default language once per session (before the toggle widget is drawn)."""
    import streamlit as st

    if st.session_state.get(STATE_KEY) not in LANGS:
        st.session_state[STATE_KEY] = DEFAULT_LANG


def has(key: str) -> bool:
    """True when the key exists (for optional labels such as an issuer type that may be new in the data)."""
    return key in strings()


def t(key: str, _lang: str | None = None, **fmt) -> str:
    """The string of `key` in the current language, with {placeholders} filled from fmt. Missing key -> I18nKeyError."""
    table = strings()
    if key not in table:
        raise I18nKeyError(key)
    lang = _lang or current_lang()
    text = table[key].get(lang)
    if not text:
        raise I18nKeyError(f"{key}:{lang}")
    return text.format(**fmt) if fmt else text


def t_or(key: str, fallback: str, **fmt) -> str:
    """t(key) if the key exists, else the fallback value unchanged (data codes we have no label for)."""
    return t(key, **fmt) if has(key) else fallback
